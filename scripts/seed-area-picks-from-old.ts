/**
 * Seed tenant_area_picks from the old service_areas / business_policies.coverage_areas for tenants with NO picks row.
 * Seeded rows are left UNCONFIRMED (confirmed_at null) so the owner confirms on Desk › Service areas;
 * Brain #942 keeps using its old-list fallback for them until then, so nobody loses coverage answers.
 *
 * Idempotent: the SQL inserts with ON CONFLICT (tenant_id) DO NOTHING, so tenants that already have picks are
 * never touched and a re-run is a no-op. This script only READS a JSON export and WRITES a .sql file; it never
 * connects to a database. Apply the SQL by hand, staging first, only with Alvin's GO.
 *
 * Input: JSON array of { id, business_name, service_areas, coverage_areas, has_picks } (export with a read-only select).
 * Usage: node --experimental-strip-types scripts/seed-area-picks-from-old.ts input.json [out.sql]
 * Old fee_ksh carries to fee_kes; old `exclude` ids become serve:false picks.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { moveOverAreas, normalizeAreaPicks, matchAreaText, type AreaPicks } from "../dashboard/src/lib/areaPicks.ts";

type OldArea = { id?: unknown; fee_ksh?: unknown };
type Row = { id: string; business_name?: string | null; service_areas?: { areas?: OldArea[]; exclude?: unknown[] } | null; coverage_areas?: unknown; has_picks?: boolean };

export type SeedPlan = { tenant: string; name: string; old: string[]; picks: AreaPicks; unmatched: string[]; questions: number };
export type SeedSummary = { tenants: number; skippedHasPicks: number; skippedNoOldList: number; seeded: SeedPlan[] };

function rawName(id: string): string {
  return id.replace(/^(county|place):/, "").trim();
}

export function planSeed(rows: Row[]): SeedSummary {
  const out: SeedSummary = { tenants: rows.length, skippedHasPicks: 0, skippedNoOldList: 0, seeded: [] };
  for (const r of rows) {
    if (r.has_picks) {
      out.skippedHasPicks++;
      continue;
    }
    const areas = Array.isArray(r.service_areas?.areas) ? r.service_areas!.areas! : [];
    const old = [
      ...new Set([
        ...areas.map((a) => (typeof a?.id === "string" ? a.id : "")).filter(Boolean),
        ...(Array.isArray(r.coverage_areas) ? r.coverage_areas.filter((c): c is string => typeof c === "string") : []),
      ]),
    ];
    if (!old.length) {
      out.skippedNoOldList++;
      continue;
    }
    const mo = moveOverAreas(old);
    const picks = [...mo.picks.picks];
    for (const a of areas) {
      const fee = typeof a?.fee_ksh === "number" && a.fee_ksh > 0 ? a.fee_ksh : null;
      if (!fee || typeof a.id !== "string") continue;
      const node = matchAreaText(rawName(a.id));
      if (!node) continue;
      const i = picks.findIndex((p) => p.node === node.id);
      if (i >= 0) picks[i] = { ...picks[i], fee_kes: fee };
      else picks.push({ node: node.id, serve: true, fee_kes: fee, note: null, conditions: [] });
    }
    for (const x of Array.isArray(r.service_areas?.exclude) ? r.service_areas!.exclude! : []) {
      if (typeof x !== "string") continue;
      const node = matchAreaText(rawName(x));
      if (node) picks.push({ node: node.id, serve: false, fee_kes: null, note: null, conditions: [] });
    }
    out.seeded.push({
      tenant: r.id,
      name: r.business_name ?? "",
      old,
      picks: normalizeAreaPicks({ picks }),
      unmatched: mo.unmatched,
      questions: mo.questions.length,
    });
  }
  return out;
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function seedSql(plan: SeedSummary): string {
  const lines = [
    "-- Seed tenant_area_picks from old service areas. Generated by scripts/seed-area-picks-from-old.ts.",
    "-- UNCONFIRMED (confirmed_at null). Idempotent: ON CONFLICT DO NOTHING never touches tenants that have picks.",
    "-- Down: delete from public.tenant_area_picks where confirmed_at is null and moved_from is not null and updated_by is null",
    "--       and tenant_id in (<ids below>);",
    "begin;",
  ];
  for (const s of plan.seeded) {
    lines.push(
      `-- ${s.name.replace(/\n/g, " ")}: ${s.picks.picks.length} picks${s.unmatched.length ? `, not on map: ${s.unmatched.join(", ")}` : ""}`,
      `insert into public.tenant_area_picks (tenant_id, tree_version, picks, moved_from, confirmed_at, updated_by)`,
      `values (${q(s.tenant)}::uuid, ${q(s.picks.tree_version)}, ${q(JSON.stringify(s.picks))}::jsonb, ${q(JSON.stringify(s.old))}::jsonb, null, null)`,
      `on conflict (tenant_id) do nothing;`,
    );
  }
  lines.push("commit;", "");
  return lines.join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const [input, outFile] = process.argv.slice(2);
  if (!input) throw new Error("usage: seed-area-picks-from-old.ts input.json [out.sql]");
  const plan = planSeed(JSON.parse(readFileSync(input, "utf8")));
  console.log(
    JSON.stringify(
      {
        tenants: plan.tenants,
        skippedHasPicks: plan.skippedHasPicks,
        skippedNoOldList: plan.skippedNoOldList,
        wouldSeed: plan.seeded.length,
        perTenant: plan.seeded.map((s) => ({ tenant: s.tenant, name: s.name, oldEntries: s.old.length, picks: s.picks.picks.length, withFee: s.picks.picks.filter((p) => p.fee_kes != null).length, unmatched: s.unmatched })),
      },
      null,
      2,
    ),
  );
  if (outFile) writeFileSync(outFile, seedSql(plan));
}
