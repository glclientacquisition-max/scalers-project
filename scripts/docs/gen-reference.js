#!/usr/bin/env node
// Generates docs/reference/schema.md (from SQL) and docs/reference/env.md (from env usage in code).
// Usage: node scripts/docs/gen-reference.js [--check]   (--check exits 1 if the files are out of date)
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', '..');
const check = process.argv.includes('--check');

function walk(dir, exts, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name === 'node_modules' || e.name === '.next' || e.name.startsWith('.')) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, exts, out);
    else if (exts.some((x) => e.name.endsWith(x))) out.push(p);
  }
  return out;
}
const rel = (p) => path.relative(root, p).split(path.sep).join('/');
const header = (title, src) =>
  `---\nowner: platform\nlast_reviewed: generated\n---\n\n# ${title}\n\n<!-- GENERATED by scripts/docs/gen-reference.js. Do not edit. Run: npm run docs:reference -->\n\nSource: ${src}\n\n`;

// ---- schema ----
function schema() {
  const files = [...walk(path.join(root, 'supabase', 'migrations'), ['.sql']), ...walk(path.join(root, 'docs', 'supabase'), ['.sql'])].sort();
  const tables = new Map(); // name -> {cols:Set, files:Set}
  const fns = new Map();
  const views = new Map();
  const add = (m, k, f) => { if (!m.has(k)) m.set(k, new Set()); m.get(k).add(rel(f)); };
  for (const f of files) {
    const sql = fs.readFileSync(f, 'utf8').replace(/--[^\n]*/g, '');
    const tRe = /create\s+table\s+(?:if\s+not\s+exists\s+)?(?:public\.)?"?([a-z_][a-z0-9_]*)"?\s*\(([\s\S]*?)\);/gi;
    let m;
    while ((m = tRe.exec(sql))) {
      const name = m[1].toLowerCase();
      if (!tables.has(name)) tables.set(name, { cols: new Set(), files: new Set() });
      const t = tables.get(name);
      t.files.add(rel(f));
      for (const line of m[2].split(/,\s*\n/)) {
        const c = line.trim().match(/^"?([a-z_][a-z0-9_]*)"?\s+[a-z]/i);
        if (c && !/^(constraint|primary|unique|foreign|check|exclude)$/i.test(c[1])) t.cols.add(c[1].toLowerCase());
      }
    }
    const aRe = /alter\s+table\s+(?:if\s+exists\s+)?(?:only\s+)?(?:public\.)?"?([a-z_][a-z0-9_]*)"?([\s\S]*?);/gi;
    while ((m = aRe.exec(sql))) {
      const name = m[1].toLowerCase();
      const cRe = /add\s+column\s+(?:if\s+not\s+exists\s+)?"?([a-z_][a-z0-9_]*)"?/gi;
      let c;
      while ((c = cRe.exec(m[2]))) {
        if (!tables.has(name)) tables.set(name, { cols: new Set(), files: new Set() });
        tables.get(name).cols.add(c[1].toLowerCase());
        tables.get(name).files.add(rel(f));
      }
    }
    const fRe = /create\s+(?:or\s+replace\s+)?function\s+(?:public\.)?"?([a-z_][a-z0-9_]*)"?/gi;
    while ((m = fRe.exec(sql))) add(fns, m[1].toLowerCase(), f);
    const vRe = /create\s+(?:or\s+replace\s+)?(?:materialized\s+)?view\s+(?:if\s+not\s+exists\s+)?(?:public\.)?"?([a-z_][a-z0-9_]*)"?/gi;
    while ((m = vRe.exec(sql))) add(views, m[1].toLowerCase(), f);
  }
  let out = header('Database schema reference', '`supabase/migrations/*.sql` and `docs/supabase/**/*.sql` (static parse; the live DB may differ, see `scripts/verify-staging-schema.js`).');
  out += `## Tables (${tables.size})\n\n| Table | Columns | Defined in |\n| --- | --- | --- |\n`;
  for (const [n, t] of [...tables].sort((a, b) => a[0].localeCompare(b[0]))) {
    out += `| \`${n}\` | ${[...t.cols].sort().map((c) => '`' + c + '`').join(', ')} | ${[...t.files].sort().map((x) => '`' + x + '`').join('<br>')} |\n`;
  }
  out += `\n## Views (${views.size})\n\n| View | Defined in |\n| --- | --- |\n`;
  for (const [n, fs_] of [...views].sort((a, b) => a[0].localeCompare(b[0]))) out += `| \`${n}\` | ${[...fs_].sort().map((x) => '`' + x + '`').join('<br>')} |\n`;
  out += `\n## Functions (${fns.size})\n\n| Function | Defined in |\n| --- | --- |\n`;
  for (const [n, fs_] of [...fns].sort((a, b) => a[0].localeCompare(b[0]))) out += `| \`${n}\` | ${[...fs_].sort().map((x) => '`' + x + '`').join('<br>')} |\n`;
  return out;
}

// ---- env ----
function env() {
  const srcs = [
    path.join(root, 'server.js'), path.join(root, 'db.js'),
    ...walk(path.join(root, 'src'), ['.js', '.ts', '.mjs']),
    ...walk(path.join(root, 'scripts'), ['.js', '.mjs']),
    ...walk(path.join(root, 'dashboard', 'src'), ['.ts', '.tsx', '.js', '.mjs']),
  ].filter((f) => fs.existsSync(f) && !/\.test\./.test(f));
  const vars = new Map(); // name -> Set(area)
  const re = /process\.env(?:\.([A-Z][A-Z0-9_]*)|\[\s*['"]([A-Z][A-Z0-9_]*)['"]\s*\])/g;
  for (const f of srcs) {
    const r = rel(f);
    const area = r.startsWith('dashboard/') ? 'desk' : r.startsWith('scripts/') ? 'scripts' : 'voice';
    const s = fs.readFileSync(f, 'utf8');
    let m;
    while ((m = re.exec(s))) {
      const n = m[1] || m[2];
      if (!vars.has(n)) vars.set(n, { areas: new Set(), files: new Set() });
      vars.get(n).areas.add(area);
      vars.get(n).files.add(r);
    }
  }
  let out = header('Environment variable reference', '`process.env.*` reads in `server.js`, `db.js`, `src/`, `scripts/`, `dashboard/src/` (names only, never values).');
  out += `Areas: **voice** = Railway Voice (\`server.js\`, \`src/\`), **desk** = Vercel Desk (\`dashboard/src\`), **scripts** = one-off scripts. Meaning and per-environment values: [\`operations/ENVIRONMENTS.md\`](operations/ENVIRONMENTS.md).\n\n`;
  out += `${vars.size} variables.\n\n| Variable | Areas | Read in |\n| --- | --- | --- |\n`;
  for (const [n, v] of [...vars].sort((a, b) => a[0].localeCompare(b[0]))) {
    const files = [...v.files].sort();
    const shown = files.slice(0, 3).map((x) => '`' + x + '`').join('<br>') + (files.length > 3 ? `<br>+${files.length - 3} more` : '');
    out += `| \`${n}\` | ${[...v.areas].sort().join(', ')} | ${shown} |\n`;
  }
  return out;
}

const targets = [
  [path.join(root, 'docs', 'reference', 'schema.md'), schema()],
  [path.join(root, 'docs', 'reference', 'env.md'), env()],
];
let stale = 0;
for (const [p, body] of targets) {
  const cur = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : '';
  if (cur === body) continue;
  if (check) { console.error(`out of date: ${rel(p)} (run npm run docs:reference)`); stale++; }
  else { fs.writeFileSync(p, body); console.log(`wrote ${rel(p)}`); }
}
process.exit(stale ? 1 : 0);
