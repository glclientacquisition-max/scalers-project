, acl_stmts as (
  select o.kind, o.objname, o.objsig, o.acl from (
    select 'TABLE' kind, relname objname, 'public.'||quote_ident(relname) objsig, c.relacl acl from pg_class c where c.oid in (select oid from T union all select oid from V)
    union all select 'FUNCTION', p.proname, p.oid::regprocedure::text, p.proacl from pg_proc p where p.oid in (select oid from F)
  ) o
),
out as (
-- 10 sequences (none needed: identity) ; 20 tables
select 20 ord, c.relname::text nm, format(E'create table if not exists public.%I (\n%s\n);', c.relname,
  string_agg(format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
    case when a.attidentity='d' then ' generated by default as identity' when a.attidentity='a' then ' generated always as identity' else '' end,
    case when ad.adbin is not null then ' default '||pg_get_expr(ad.adbin, ad.adrelid) else '' end,
    case when a.attnotnull then ' not null' else '' end), E',\n' order by a.attnum)) ddl
from T c join pg_attribute a on a.attrelid=c.oid and a.attnum>0 and not a.attisdropped left join pg_attrdef ad on ad.adrelid=c.oid and ad.adnum=a.attnum group by c.relname
union all
-- 25 missing columns on existing tables
select 25, c.relname||'.'||a.attname, format('alter table public.%I add column if not exists %I %s%s%s;', c.relname, a.attname, format_type(a.atttypid,a.atttypmod),
    case when a.attidentity='d' then ' generated by default as identity' when a.attidentity='a' then ' generated always as identity' else '' end ||
    case when ad.adbin is not null then ' default '||pg_get_expr(ad.adbin, ad.adrelid) else '' end,
    case when a.attnotnull then ' not null' else '' end)
from T c join pg_attribute a on a.attrelid=c.oid and a.attnum>0 and not a.attisdropped left join pg_attrdef ad on ad.adrelid=c.oid and ad.adnum=a.attnum
union all
-- 30 non-FK constraints, 35 FK
select case when k.contype='f' then 35 else 30 end, c.relname||'.'||k.conname, format(E'do $m$ begin\n  if not exists (select 1 from pg_constraint where conname = %L and conrelid = %L::regclass) then\n    alter table public.%I add constraint %I %s;\n  end if;\nend $m$;', k.conname, 'public.'||quote_ident(c.relname), c.relname, k.conname, pg_get_constraintdef(k.oid))
from T c join pg_constraint k on k.conrelid=c.oid
union all
-- 40 indexes not backing constraints
select 40, i.relname, regexp_replace(pg_get_indexdef(x.indexrelid), '^CREATE (UNIQUE )?INDEX ', 'create \1index if not exists ')||';'
from T c join pg_index x on x.indrelid=c.oid join pg_class i on i.oid=x.indexrelid where not exists (select 1 from pg_constraint k where k.conindid=x.indexrelid)
union all
-- 50 functions
select 50, p.oid::regprocedure::text, pg_get_functiondef(p.oid)||';' from pg_proc p where p.oid in (select oid from F)
union all
-- 60 views
select 60, c.relname, format(E'create or replace view public.%I%s as\n%s', c.relname, coalesce(' with ('||array_to_string(c.reloptions, ', ')||')',''), rtrim(pg_get_viewdef(c.oid), ';')||';') from pg_class c where c.oid in (select oid from V)
union all
-- 70 triggers
select 70, TG.relname||'.'||TG.tgname, format('drop trigger if exists %I on public.%I;', TG.tgname, TG.relname)||E'\n'||pg_get_triggerdef(TG.oid)||';'||case TG.tgenabled when 'D' then format(E'\nalter table public.%I disable trigger %I;', TG.relname, TG.tgname) when 'R' then format(E'\nalter table public.%I enable replica trigger %I;', TG.relname, TG.tgname) when 'A' then format(E'\nalter table public.%I enable always trigger %I;', TG.relname, TG.tgname) else '' end from TG
union all
-- 80 RLS
select 80, c.relname, format('alter table public.%I %s row level security;', c.relname, case when c.relrowsecurity then 'enable' else 'disable' end)||case when c.relforcerowsecurity then format(E'\nalter table public.%I force row level security;', c.relname) else '' end from pg_class c where c.oid in (select oid from T)
union all
-- 85 policies
select 85, pol.tablename||'.'||pol.policyname, format('drop policy if exists %I on public.%I;', pol.policyname, pol.tablename)||E'\n'||format('create policy %I on public.%I as %s for %s to %s%s%s;', pol.policyname, pol.tablename, pol.permissive, pol.cmd, array_to_string(pol.roles, ', '), coalesce(E'\n  using ('||pol.qual||')',''), coalesce(E'\n  with check ('||pol.with_check||')',''))
from pg_policies pol where pol.schemaname='public' and pol.tablename in (select relname from T)
union all
-- 90 grants
select 90, a.objsig, format('revoke all on %s %s from public, anon, authenticated, service_role;', lower(a.kind), a.objsig) || coalesce((
  select string_agg(format(E'\ngrant %s on %s %s to %s;', g.privs, lower(a.kind), a.objsig, g.grantee), '' order by g.grantee) from (
    select case when e.grantee=0 then 'public' else quote_ident(r.rolname) end grantee, string_agg(distinct lower(e.privilege_type), ', ' order by lower(e.privilege_type)) privs
    from aclexplode(a.acl) e left join pg_roles r on r.oid=e.grantee
    where e.grantee=0 or r.rolname in ('anon','authenticated','service_role')
    group by 1) g), case when a.acl is null and a.kind='FUNCTION' then E'\ngrant execute on function '||a.objsig||' to public;' when a.acl is null then E'\n-- default acl' else '' end)
from acl_stmts a
union all
-- 95 cron
select 95, CJ.jobname, format(E'do $m$ begin\n  if exists (select 1 from cron.job where jobname = %L) then perform cron.unschedule(%L); end if;\n  perform cron.schedule(%L, %L, %L);\nend $m$;', CJ.jobname, CJ.jobname, CJ.jobname, CJ.schedule, CJ.command)||case when not CJ.active then format(E'\nupdate cron.job set active = false where jobname = %L;', CJ.jobname) else '' end from CJ
)
select ord, nm, ddl from out order by ord, nm;
