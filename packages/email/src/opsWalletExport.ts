/**
 * Static export of the ops wallet alert (ops_wallet) for Desk's ops-alerts cron.
 * Desk does not run React Email at request time, so the layout is rendered here
 * once per environment and state with placeholder fields, written to
 * dashboard/src/lib/opsWalletTemplates.ts, and filled (escaped) by Desk.
 * test/opsWallet.test.ts fails when the committed file drifts from this source.
 */
import { renderEmail } from "./index.ts";

export const WALLET_ENVS = ["production", "staging"] as const;
export const WALLET_STATES = ["low", "empty", "topped_up"] as const;

/** Placeholder fields. Desk replaces each with an escaped value. */
export const WALLET_FIELDS = {
  workspace: "__WORKSPACE__",
  balance: "__BALANCE__",
  threshold: "__THRESHOLD__",
  checkedAt: "__CHECKED_AT__",
  risk: "__RISK__",
  nextAlert: "__NEXT_ALERT__",
} as const;

export type WalletTemplate = { subject: string; preheader: string; html: string; text: string; from: string };

export async function renderWalletTemplates(): Promise<Record<string, WalletTemplate>> {
  const out: Record<string, WalletTemplate> = {};
  for (const env of WALLET_ENVS) {
    for (const state of WALLET_STATES) {
      const f = WALLET_FIELDS;
      const e = await renderEmail("ops_wallet", {
        env,
        state,
        workspace: f.workspace,
        balance: f.balance,
        threshold: f.threshold,
        checkedAt: f.checkedAt,
        // Production low/empty always carries the renewal line; staging has none.
        risk: env === "production" && state !== "topped_up" ? f.risk : undefined,
        nextAlert: state === "topped_up" ? f.nextAlert : undefined,
      });
      out[`${env}:${state}`] = { subject: e.subject, preheader: e.preheader, html: e.html, text: e.text, from: e.from };
    }
  }
  return out;
}

export function generatedModule(templates: Record<string, WalletTemplate>): string {
  return [
    "/* eslint-disable */",
    "// GENERATED by packages/email (npm run export:ops-wallet). Do not edit by hand:",
    "// change packages/email/src/templates/ops.ts (opsWallet) and re-export.",
    "// Placeholders are filled and escaped by dashboard/src/lib/opsWalletEmail.ts.",
    "",
    `export const OPS_WALLET_FIELDS = ${JSON.stringify(WALLET_FIELDS, null, 2)} as const;`,
    "",
    "export type OpsWalletTemplate = { subject: string; preheader: string; html: string; text: string; from: string };",
    "",
    `export const OPS_WALLET_TEMPLATES: Record<string, OpsWalletTemplate> = ${JSON.stringify(templates, null, 2)};`,
    "",
  ].join("\n");
}
